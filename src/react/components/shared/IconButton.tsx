import type { ButtonHTMLAttributes, ReactNode } from 'react';

interface IconButtonProps extends ButtonHTMLAttributes<HTMLButtonElement> {
  icon: ReactNode;
  danger?: boolean;
  label?: string;
}

export function IconButton({ icon, danger = false, label, className = '', ...props }: IconButtonProps) {
  return (
    <button
      type="button"
      title={label}
      className={`
        w-[30px] h-[30px] rounded-[7px] border border-gray-200 bg-white
        inline-flex items-center justify-center cursor-pointer transition-all duration-100
        ${danger
          ? 'text-red-500 hover:bg-red-50 hover:border-red-300'
          : 'text-gray-500 hover:bg-gray-50 hover:text-gray-900'
        }
        ${className}
      `}
      {...props}
    >
      <span className="w-3.5 h-3.5">{icon}</span>
    </button>
  );
}

